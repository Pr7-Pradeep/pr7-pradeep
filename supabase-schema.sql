-- PR7 AI PROMPTS: Supabase setup
-- Run this in Supabase Dashboard > SQL Editor.
-- Public visitors can read published prompt records. Only signed-in users with admin role can write.
-- IMPORTANT: Create your own admin user in Supabase Auth, then run the UPDATE below with that user's UUID.

create table if not exists public.prompts (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) <= 90),
  category text not null default 'Cinematic',
  image_url text not null default '',
  prompt text not null,
  tag text not null default '',
  credit text not null default '',
  created_at timestamptz not null default now()
);

alter table public.prompts enable row level security;

drop policy if exists "Public can read prompts" on public.prompts;
create policy "Public can read prompts"
on public.prompts for select
to anon, authenticated
using (true);

-- Admin allow-list table. Public users cannot read or change it.
create table if not exists public.pr7_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.pr7_admins enable row level security;

drop policy if exists "Admins can read own admin record" on public.pr7_admins;
create policy "Admins can read own admin record"
on public.pr7_admins for select
to authenticated
using (user_id = auth.uid());

drop policy if exists "Admins can insert prompts" on public.prompts;
create policy "Admins can insert prompts"
on public.prompts for insert
to authenticated
with check (exists (select 1 from public.pr7_admins a where a.user_id = auth.uid()));

drop policy if exists "Admins can update prompts" on public.prompts;
create policy "Admins can update prompts"
on public.prompts for update
to authenticated
using (exists (select 1 from public.pr7_admins a where a.user_id = auth.uid()))
with check (exists (select 1 from public.pr7_admins a where a.user_id = auth.uid()));

drop policy if exists "Admins can delete prompts" on public.prompts;
create policy "Admins can delete prompts"
on public.prompts for delete
to authenticated
using (exists (select 1 from public.pr7_admins a where a.user_id = auth.uid()));

